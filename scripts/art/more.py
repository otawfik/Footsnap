"""Second pass for players who still have no cut-out: look wider on Wikidata and Wikimedia Commons.

    python scripts/art/more.py public/art more.json [squads-dir]

For every squad player without an entry in <art>/index.json:
  1. Find the player's Wikidata item: English Wikipedia article (same rules as resolve.py), else a Wikidata
     search by name. Either way the item must be a footballer whose birth date (P569) is exactly the squad's
     date of birth. No birth date on Wikidata = no photo (stricter than verify.py, which keeps those).
  2. Gather candidate photos, best first: every image on the item (P18), the lead image of the player's
     Wikipedia articles (Commons files only), files on Commons that are tagged as depicting the player
     (structured data, P180) and files in the player's Commons category (P373). Files from the last two
     must carry the player's surname in the file name and must not name a second person ("X & Y", "X and Y").
  3. Keep only freely licensed files (LICENCE below: CC0, public domain, CC BY, CC BY-SA), drop official/
     press-office uploads (OFFICIAL below), anything categorised as AI-generated, and files too small to
     frame at the card's face size.
The output has one entry per player with up to MAX_CANDS candidates; rounds.py tries them in order.
Squads come from <squads-dir>/<competition>.json if given, else from the app's proxy (7 s apart: the free
data tier allows 10 requests a minute).
"""
import json, os, re, sys, time, unicodedata
import requests

UA = {"User-Agent": "FootSnap art pipeline (https://github.com/otawfik/Footsnap; second pass for missing players)"}
LEAGUES = [2021, 2014, 2002, 2019, 2015, 2001]
MAX_CANDS = int(os.environ.get("MAX_CANDS", 5))
ART, OUT = sys.argv[1], sys.argv[2]
SQUADS = sys.argv[3] if len(sys.argv) > 3 else None

# the licences already used by the set; versioned CC BY / BY-SA (incl. ported, e.g. "CC BY-SA 3.0 at"), CC0, PD
LICENCE = re.compile(r"^(CC0( 1\.0)?|Public domain|CC BY(-SA)? [1-4]\.[05]( [a-z]{2,3})?)$", re.I)
# government / press-office / agency uploads: free licence or not, these are official photos, so they're skipped
OFFICIAL = re.compile(r"kremlin|presidential|president of|press (service|office)|пресс|government|gobierno|governo|ministry|"
                      r"ministerio|minist[eè]re|official|news agency|tasnim|fars ?news|mehr ?news|irna|agência brasil|"
                      r"casa rosada|presidencia|mil\.ru|белый дом|palácio", re.I)
AI = re.compile(r"ai[- ]generated|generated by (ai|artificial)|stable diffusion|midjourney|dall-?e", re.I)
PAIR = re.compile(r"\s(&|and|with|und|mit|et|y|e|og|och|en|i)\s", re.I)
MIN_SIDE = 500

def get(url, params, tries=6):
    for a in range(tries):
        try:
            r = requests.get(url, params={"format": "json", "formatversion": 2, **params}, headers=UA, timeout=60)
        except requests.RequestException:
            time.sleep(5 * (a + 1)); continue
        if r.status_code == 200: return r.json()
        wait = int(r.headers.get("Retry-After") or 0) or 5 * (a + 1)
        time.sleep(min(120, wait))
    return {}

def fold(s):
    s = unicodedata.normalize("NFKD", s or "")
    return "".join(c for c in s if not unicodedata.combining(c)).lower().replace("ø", "o").replace("ł", "l").replace("ß", "ss")

# --- squads -----------------------------------------------------------------------------------------------
players = {}
for n, lg in enumerate(LEAGUES):
    if SQUADS:
        d = json.load(open(os.path.join(SQUADS, f"{lg}.json")))
    else:
        if n: time.sleep(7)
        d = requests.get(f"https://footsnap-app.vercel.app/api/fd/competitions/{lg}/teams", headers=UA, timeout=60).json()
    for t in d["teams"]:
        for p in t.get("squad") or []:
            players.setdefault(p["id"], {"id": p["id"], "name": p["name"], "dob": p.get("dateOfBirth"), "leagues": set()})["leagues"].add(lg)
index = json.load(open(os.path.join(ART, "index.json")))
missing = [p for p in players.values() if str(p["id"]) not in index and p["dob"]]
print(f"players {len(players)} | with art {sum(str(i) in index for i in players)} | missing (with a birth date) {len(missing)}", flush=True)

# --- 1. Wikidata item -------------------------------------------------------------------------------------
def titles(p):
    y = p["dob"][:4]
    return [f'{p["name"]} (footballer, born {y})', f'{p["name"]} (footballer)', p["name"]]

want = sorted({t for p in missing for t in titles(p)})
pages = {}
for i in range(0, len(want), 50):
    b = want[i:i + 50]
    d = get("https://en.wikipedia.org/w/api.php", {"action": "query", "redirects": 1, "prop": "pageimages|description|pageprops",
                                                  "piprop": "name", "titles": "|".join(b)}).get("query", {})
    norm = {x["from"]: x["to"] for x in d.get("normalized", [])}
    redir = {x["from"]: x["to"] for x in d.get("redirects", [])}
    by = {pg["title"]: pg for pg in d.get("pages", [])}
    for t in b:
        tt = norm.get(t, t); pages[t] = by.get(redir.get(tt, tt))
    time.sleep(0.1)
qid, lead, label = {}, {}, {}
for p in missing:
    for t in titles(p):
        pg = pages.get(t)
        if not pg or pg.get("missing") or "disambiguation" in (pg.get("pageprops") or {}): continue
        desc = (pg.get("description") or "").lower()
        if "football" not in desc and "soccer" not in desc: continue
        q = (pg.get("pageprops") or {}).get("wikibase_item")
        if q:
            qid[p["id"]] = q; label[p["id"]] = re.sub(r"\s*\(.*\)$", "", pg["title"])
            if pg.get("pageimage"): lead[p["id"]] = [pg["pageimage"]]
        break
print("English article:", len(qid), flush=True)

search = {}
for n, p in enumerate(x for x in missing if x["id"] not in qid):
    d = get("https://www.wikidata.org/w/api.php", {"action": "wbsearchentities", "search": p["name"], "language": "en", "type": "item", "limit": 7})
    search[p["id"]] = [x["id"] for x in d.get("search", [])]
    time.sleep(0.05)
    if n % 200 == 0: print("  wikidata search", n, flush=True)

ents = {}
allq = sorted(set(qid.values()) | {q for qs in search.values() for q in qs})
for i in range(0, len(allq), 50):
    d = get("https://www.wikidata.org/w/api.php", {"action": "wbgetentities", "ids": "|".join(allq[i:i + 50]), "props": "claims|sitelinks|labels", "languages": "en"})
    ents.update(d.get("entities", {}))
    time.sleep(0.1)

def values(e, prop):
    return [c["mainsnak"]["datavalue"]["value"] for c in (e.get("claims") or {}).get(prop, []) if c.get("mainsnak", {}).get("datavalue")]
def born(e): return {v["time"][1:11] for v in values(e, "P569") if isinstance(v, dict) and "time" in v}
FOOTBALLER = {"Q937857", "Q18515558"}
def footballer(e): return any(isinstance(v, dict) and v.get("id") in FOOTBALLER for v in values(e, "P106"))

byid = {p["id"]: p for p in missing}
for p in missing:
    if p["id"] in qid: continue
    for q in search.get(p["id"], []):
        e = ents.get(q, {})
        if footballer(e) and p["dob"][:10] in born(e):
            qid[p["id"]] = q; label[p["id"]] = ((e.get("labels") or {}).get("en") or {}).get("value", p["name"]); break
verified = {pid: q for pid, q in qid.items() if byid[pid]["dob"][:10] in born(ents.get(q, {}))}
print(f"Wikidata items {len(qid)} | birth date matches the squad {len(verified)} | dropped (no or different P569) {len(qid) - len(verified)}", flush=True)

# --- 2. candidates ----------------------------------------------------------------------------------------
LANGS = ["dewiki", "eswiki", "itwiki", "frwiki", "ptwiki", "nlwiki", "trwiki", "plwiki", "hrwiki", "srwiki", "dawiki", "svwiki", "nowiki"]
for wiki in LANGS:
    todo = [(pid, (ents[q].get("sitelinks") or {}).get(wiki, {}).get("title")) for pid, q in verified.items()]
    todo = [(pid, t) for pid, t in todo if t]
    host = f"https://{wiki[:-4]}.wikipedia.org/w/api.php"
    for i in range(0, len(todo), 50):
        b = todo[i:i + 50]
        d = get(host, {"action": "query", "redirects": 1, "prop": "pageimages", "piprop": "name", "titles": "|".join(t for _, t in b)}).get("query", {})
        norm = {x["from"]: x["to"] for x in d.get("normalized", [])}
        redir = {x["from"]: x["to"] for x in d.get("redirects", [])}
        by = {pg["title"]: pg.get("pageimage") for pg in d.get("pages", [])}
        for pid, t in b:
            tt = norm.get(t, t); img = by.get(redir.get(tt, tt))
            if img and img not in lead.get(pid, []): lead.setdefault(pid, []).append(img)
        time.sleep(0.1)

def info_from(pg):
    ii = (pg.get("imageinfo") or [{}])[0]; em = ii.get("extmetadata") or {}
    v = lambda k: re.sub(r"<[^>]+>", "", (em.get(k) or {}).get("value") or "")
    return {"file": pg["title"][5:].replace(" ", "_"), "w": ii.get("width", 0), "h": ii.get("height", 0), "mime": ii.get("mime", ""),
            "license": v("LicenseShortName").strip(), "who": v("Artist") + " " + v("Credit"), "cats": v("Categories"),
            "date": v("DateTimeOriginal")[:10], "nonfree": v("NonFree")}

II = {"prop": "imageinfo", "iiprop": "size|mime|extmetadata", "iiextmetadatafilter": "LicenseShortName|Artist|Credit|Categories|DateTimeOriginal|NonFree"}
files = {}
named = sorted({f.replace(" ", "_") for pid, q in verified.items() for f in [*values(ents[q], "P18"), *lead.get(pid, [])]})
for i in range(0, len(named), 50):
    d = get("https://commons.wikimedia.org/w/api.php", {"action": "query", "titles": "|".join("File:" + f for f in named[i:i + 50]), **II}).get("query", {})
    for pg in d.get("pages", []):
        if not pg.get("missing") and pg.get("imageinfo"): files[pg["title"][5:].replace(" ", "_")] = info_from(pg)
    time.sleep(0.1)

def surname_ok(pid, fname):
    f = fold(fname)
    names = {fold(byid[pid]["name"]), fold(label.get(pid, ""))}
    return any(len(n.split()[-1]) >= 3 and n.split()[-1] in f for n in names if n.split())

extra = {}
for n, (pid, q) in enumerate(verified.items()):
    got = []
    d = get("https://commons.wikimedia.org/w/api.php", {"action": "query", "generator": "search", "gsrsearch": f"haswbstatement:P180={q}",
                                                       "gsrnamespace": 6, "gsrlimit": 40, **II})
    got += [("depicts", info_from(pg)) for pg in d.get("query", {}).get("pages", []) if pg.get("imageinfo")]
    for cat in values(ents[q], "P373")[:1]:
        d = get("https://commons.wikimedia.org/w/api.php", {"action": "query", "generator": "categorymembers", "gcmtitle": f"Category:{cat}",
                                                           "gcmtype": "file", "gcmlimit": 100, **II})
        got += [("category", info_from(pg)) for pg in d.get("query", {}).get("pages", []) if pg.get("imageinfo")]
    extra[pid] = got
    time.sleep(0.1)
    if n % 200 == 0: print("  commons", n, "/", len(verified), flush=True)

reasons = {}
def usable(f, strict_name, pid):
    why = None
    if f["mime"] not in ("image/jpeg", "image/png", "image/webp"): why = "not a photo"
    elif f["nonfree"]: why = "non-free"
    elif not LICENCE.match(f["license"]): why = f"licence {f['license'] or '?'}"
    elif OFFICIAL.search(f["who"]): why = "official/press source"
    elif AI.search(f["cats"]) or AI.search(f["file"]): why = "AI-generated"
    elif min(f["w"], f["h"]) < MIN_SIDE: why = "too small"
    elif strict_name and not surname_ok(pid, f["file"]): why = "file name doesn't name the player"
    elif strict_name and PAIR.search(re.sub(r"[_.]", " ", f["file"])): why = "names a second person"
    if why: reasons[why] = reasons.get(why, 0) + 1
    return not why

out = []
for p in missing:
    pid = p["id"]; q = verified.get(pid)
    if not q: continue
    cands, seen = [], set()
    def add(src, f, strict):
        if f and f["file"] not in seen and usable(f, strict, pid):
            seen.add(f["file"]); cands.append({"image": f["file"], "source": src, "license": f["license"], "date": f["date"], "w": f["w"], "h": f["h"]})
    for f in values(ents[q], "P18"): add("p18", files.get(f.replace(" ", "_")), False)
    for f in lead.get(pid, []): add("lead", files.get(f.replace(" ", "_")), False)
    # Commons finds: newest first, cropped portraits before full frames
    more = sorted(extra.get(pid, []), key=lambda sf: ("cropped" in sf[1]["file"].lower(), sf[1]["date"]), reverse=True)
    for src, f in more: add(src, f, True)
    # every Commons photo the item or an article uses, licence aside: only compared against, never published
    refs = [f for f in dict.fromkeys(x.replace(" ", "_") for x in [*values(ents[q], "P18"), *lead.get(pid, [])]) if f in files]
    if cands:
        out.append({"id": pid, "name": p["name"], "dob": p["dob"], "leagues": sorted(p["leagues"]), "qid": q, "cands": cands[:MAX_CANDS], "refs": refs})
json.dump(out, open(OUT, "w"), indent=1)
print(f"players with at least one candidate {len(out)} | candidates {sum(len(r['cands']) for r in out)}")
print("rejected files:", dict(sorted(reasons.items(), key=lambda kv: -kv[1])))
for lg in LEAGUES:
    print(lg, sum(lg in r["leagues"] for r in out))
