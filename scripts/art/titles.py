"""Fourth pass: Commons photos whose file name names the player, for players still without a candidate.

    python scripts/art/titles.py <squads-dir> <skip.json> <facts.json> titles.json

more.py only looked where Wikidata points (P18, article lead images, the player's Commons category, files
tagged as depicting him). Plenty of free match photos sit on Commons with the player's name in the file
name and nothing else ("Florian Lejeune 2023.jpg"): this finds them with Commons' own search
(intitle:"Full Name", File namespace), for every squad player not in <skip.json> (a list or dict of ids:
players with a card photo or already handled).

A file counts only if its name holds EVERY word of the player's name (not just the surname), names no
second person ("X and Y"), and passes more.py's rules: CC0 / public domain / CC BY / CC BY-SA, not an
official or press-office upload, not AI-generated, at least 500 px. Nothing here is trusted yet: the output
has more.py's shape with source "title", so identity.py accepts a file only if its face matches the
player's Wikidata photo (refs, from lib/facts.json's item ids) or, when he has none, another of his
candidates: two different photos agreeing on one face.
"""
import json, os, re, sys, time, unicodedata
import requests

SQUADS, SKIP, FACTS, OUT = sys.argv[1:5]
UA = {"User-Agent": "FootSnap art pipeline (https://github.com/otawfik/Footsnap; title search for missing players)"}
API = "https://commons.wikimedia.org/w/api.php"
LICENCE = re.compile(r"^(CC0( 1\.0)?|Public domain|CC BY(-SA)? [1-4]\.[05]( [a-z]{2,3})?)$", re.I)
OFFICIAL = re.compile(r"kremlin|presidential|president of|press (service|office)|пресс|government|gobierno|governo|ministry|"
                      r"ministerio|minist[eè]re|official|news agency|tasnim|fars ?news|mehr ?news|irna|agência brasil|"
                      r"casa rosada|presidencia|mil\.ru|белый дом|palácio", re.I)
AI = re.compile(r"ai[- ]generated|generated by (ai|artificial)|stable diffusion|midjourney|dall-?e", re.I)
PAIR = re.compile(r"\s(&|and|with|und|mit|et|y|e|og|och|en|i|vs\.?|v)\s", re.I)
MIN_SIDE, MAX_CANDS = 500, 6
II = {"prop": "imageinfo", "iiprop": "size|mime|extmetadata", "iiextmetadatafilter": "LicenseShortName|Artist|Credit|Categories|DateTimeOriginal|NonFree"}


def get(params, tries=6):
    for a in range(tries):
        try:
            r = requests.get(API, params={"format": "json", "formatversion": 2, **params}, headers=UA, timeout=60)
        except requests.RequestException:
            time.sleep(5 * (a + 1)); continue
        if r.status_code == 200: return r.json()
        time.sleep(min(120, int(r.headers.get("Retry-After") or 0) or 5 * (a + 1)))
    return {}


def fold(s):
    s = unicodedata.normalize("NFKD", s or "")
    return "".join(c for c in s if not unicodedata.combining(c)).lower().replace("ø", "o").replace("ł", "l").replace("ß", "ss")


def words(s):
    return [w for w in re.split(r"[^a-z]+", fold(s)) if w]


def info(pg):
    ii = (pg.get("imageinfo") or [{}])[0]; em = ii.get("extmetadata") or {}
    v = lambda k: re.sub(r"<[^>]+>", "", (em.get(k) or {}).get("value") or "")
    return {"file": pg["title"][5:].replace(" ", "_"), "w": ii.get("width", 0), "h": ii.get("height", 0), "mime": ii.get("mime", ""),
            "license": v("LicenseShortName").strip(), "who": v("Artist") + " " + v("Credit"), "cats": v("Categories"),
            "date": v("DateTimeOriginal")[:10], "nonfree": v("NonFree")}


def usable(f, name):
    if f["mime"] not in ("image/jpeg", "image/png", "image/webp") or f["nonfree"]: return False
    if not LICENCE.match(f["license"]) or OFFICIAL.search(f["who"]) or AI.search(f["cats"] + " " + f["file"]): return False
    if min(f["w"], f["h"]) < MIN_SIDE: return False
    fw = set(words(f["file"]))
    if not all(w in fw for w in words(name)): return False
    return not PAIR.search(" " + re.sub(r"[_.()\-]", " ", f["file"]) + " ")


skip = json.load(open(SKIP)); skip = set(map(str, skip))
facts = json.load(open(FACTS))
players = {}
for fn in sorted(os.listdir(SQUADS)):
    if not fn.endswith(".json"): continue
    lg = int(fn.split(".")[0])
    for t in json.load(open(os.path.join(SQUADS, fn)))["teams"]:
        for p in t.get("squad") or []:
            if str(p["id"]) in skip or not p.get("dateOfBirth") or len(words(p["name"])) < 2: continue
            players.setdefault(p["id"], {"id": p["id"], "name": p["name"], "dob": p["dateOfBirth"], "leagues": set()})["leagues"].add(lg)
print("players to search", len(players), flush=True)

# refs: the Wikidata photo (P18) of players whose item lib/facts.json matched on name + date of birth
qids = {pid: facts[str(pid)]["q"] for pid in players if str(pid) in facts}
p18 = {}
ql = sorted(set(qids.values()))
for i in range(0, len(ql), 50):
    r = requests.get("https://www.wikidata.org/w/api.php", params={"action": "wbgetentities", "ids": "|".join(ql[i:i + 50]), "props": "claims", "format": "json"}, headers=UA, timeout=60).json()
    for q, e in (r.get("entities") or {}).items():
        v = [c["mainsnak"].get("datavalue", {}).get("value") for c in (e.get("claims") or {}).get("P18", [])]
        if v and v[0]: p18[q] = v[0].replace(" ", "_")
    time.sleep(0.2)

out, n_files = [], 0
for n, p in enumerate(players.values()):
    d = get({"action": "query", "generator": "search", "gsrsearch": f'intitle:"{p["name"]}"', "gsrnamespace": 6, "gsrlimit": 30, **II})
    got = [info(pg) for pg in (d.get("query") or {}).get("pages", []) if pg.get("imageinfo")]
    good = [f for f in got if usable(f, p["name"])]
    # cropped portraits first, then newest
    good.sort(key=lambda f: ("cropped" in f["file"].lower(), f["date"]), reverse=True)
    q = qids.get(p["id"])
    if good:
        n_files += len(good)
        out.append({"id": p["id"], "name": p["name"], "dob": p["dob"], "leagues": sorted(p["leagues"]), "qid": q,
                    "cands": [{"image": f["file"], "source": "title", "license": f["license"], "date": f["date"], "w": f["w"], "h": f["h"]} for f in good[:MAX_CANDS]],
                    "refs": [p18[q]] if q in p18 else []})
    time.sleep(0.15)
    if n % 200 == 199: print(f"  searched {n + 1} | players with files {len(out)}", flush=True)
json.dump(out, open(OUT, "w"), indent=1)
print(f"players with title matches {len(out)} | files {n_files} | with a reference photo {sum(bool(r['refs']) for r in out)}", flush=True)
